#!/usr/bin/env python3
"""gen_dgn_giant_assets.py — the giant Mode 7 boss, converted for the ROM (docs/dungeons/20).

    python3 tools/gen_dgn_giant_assets.py OUT_DIR [--preview OUT.gif]

Reads ONLY committed inputs (the build never runs Blender):
  art/dungeons/creatures/out/crownling_boss/idle_down.png + palettes.json   the crown, 128x192, 16 indices
  art/dungeons/style/out/a_storybook/{idle,walk}_{down,right}.png           the players (via gen_dgn_fight_assets)
and emits (byte-identical on re-run):
  dgng_m7.bin      32,768 B   the whole Mode 7 VRAM: 16,384 map bytes interleaved with 16,384 CHR bytes. The map is
                              128x128 tile numbers; the CHR is up to 256 DISTINCT 8x8 tiles of 8bpp (64 B), tile 0
                              being the blank. One DMA with mode 1 (VMDATAL, VMDATAH) streams it straight in.
  dgng_hero.bin    9,216 B    the players' 18 frames as 4x4-tile slot images (512 B), streamed with back buffers
  dgng_pal.bin     96 B       BG palette (16 words: index 0 is the backdrop, the floor colour) + OBJ palettes 0, 1
  dgng_score.bin   16,384 B   290 ticks x 33 B: 4 OAM entries, the hi byte, the 16-byte Mode 7 shadow
  dgng_cmds.bin    4,096 B    the players' DMA rows (6 B each), the entry-state rows last
  dgng_ptr.bin     1,024 B    T + 2 u16 byte offsets
  dgng_frames.inc  equates. Never an address.
  dgng_report.json the numbers the tests and the doc quote
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools"))
from dgn_giant import director as G  # noqa: E402
from dgn_fight import director as DF  # noqa: E402
import gen_dgn_fight_assets as GF  # noqa: E402
from gen_dgn_hero_assets import bgr555  # noqa: E402
import sheets  # noqa: E402

CROWN = REPO / "art" / "dungeons" / "creatures" / "out" / "crownling_boss"
SCORE_CLAIM, CMDS_CLAIM, PTR_CLAIM = 16384, 4096, 1024
MAP_COLS = MAP_ROWS = 128


def crown_image() -> np.ndarray:
    a = np.asarray(Image.open(CROWN / "idle_down.png"))
    assert a.shape == (G.IMG_H, G.IMG_W) and a.max() <= 15, a.shape
    return a


def m7_blob(img: np.ndarray):
    """(blob, unique tile count). The image sits on the plane at IMG_ORIGIN; every other map cell is tile 0."""
    ox, oy = G.IMG_ORIGIN
    assert ox % 8 == 0 and oy % 8 == 0
    tiles = [np.zeros((8, 8), np.uint8)]            # tile 0: the blank
    index = {tiles[0].tobytes(): 0}
    cell = np.zeros((MAP_ROWS, MAP_COLS), np.uint8)
    for ty in range(G.IMG_H // 8):
        for tx in range(G.IMG_W // 8):
            t = img[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8]
            k = t.tobytes()
            if k not in index:
                if len(tiles) >= 256:
                    raise SystemExit(f"gen_dgn_giant_assets: the crown needs more than 256 distinct tiles "
                                     f"(Mode 7 has 256): refused, not cropped")
                index[k] = len(tiles)
                tiles.append(t.copy())
            cell[oy // 8 + ty, ox // 8 + tx] = index[k]
    chr_ = b"".join(t.tobytes() for t in tiles).ljust(16384, b"\0")
    mp = cell.tobytes()
    blob = bytearray(32768)
    blob[0::2] = mp                                  # VMDATAL: the tilemap
    blob[1::2] = chr_                                # VMDATAH: the 8bpp CHR
    return bytes(blob), len(tiles)


def pal_blob(pal) -> bytes:
    w = bgr555(sheets.BG_FLOOR)
    words = [w] + [bgr555(c) for c in pal[1:]]       # CGRAM 0 = the backdrop AND the plane's index 0
    sty = json.loads((GF.STY / "palettes.json").read_text())
    for p in (sty["p1"], sty["p2"]):                 # OBJ palettes 0, 1 (CGRAM 128..159)
        words += [0] + [bgr555(c) for c in p[1:]]
    assert len(words) == 48
    return b"".join(x.to_bytes(2, "little") for x in words)


def pad(data: bytes, size: int, what: str) -> bytes:
    if len(data) > size:
        raise SystemExit(f"gen_dgn_giant_assets: {what} is {len(data)} B, over its {size} B claim")
    return data + bytes(size - len(data))


def inc_text() -> str:
    return "\n".join([
        "; GENERATED by tools/gen_dgn_giant_assets.py: do not edit.",
        "; The score's length and record layout. No addresses.",
        f"DGNG_T = {G.LOOP}",
        f"DGNG_REC = {G.RECORD_BYTES}",
        f"DGNG_REC_END = {G.LOOP * G.RECORD_BYTES}",
        "DGNG_REC_OAM = 16",
        "DGNG_REC_HI = 1",
        "DGNG_REC_M7 = 16",
        f"DGNG_BACKDROP_BGR = {bgr555(sheets.BG_FLOOR)}", ""])


def render_preview(img, states, ticks, scale=3):
    plane = G.plane_from_image(img)
    pals = json.loads((CROWN / "palettes.json").read_text())["base"]
    sty = json.loads((GF.STY / "palettes.json").read_text())
    floor = bgr555(sheets.BG_FLOOR)
    bg = np.array([(floor & 31) * 255 // 31, ((floor >> 5) & 31) * 255 // 31, ((floor >> 10) & 31) * 255 // 31], np.uint8)
    bgpal = np.array([bg] + [np.array(c, np.uint8) for c in pals[1:]], np.uint8)
    hero = GF.hero_frames()
    frames = []
    for t in ticks:
        words = G.matrix_words(*G.boss_state(t))
        idx = G.render_m7(plane, words)
        c = bgpal[idx].copy()
        for who, pal in (("p1", sty["p1"]), ("p2", sty["p2"])):
            s = states[who][t]
            f = hero[s.frame][:, :16]
            ax = (15 - DF.HERO_AX) if s.flip else DF.HERO_AX
            im = f[:, ::-1] if s.flip else f
            x0, y0 = s.x - ax, s.y - DF.HERO_AY
            ys, xs = np.nonzero(im)
            for yy, xx in zip(ys, xs):
                X, Y = x0 + xx, y0 + yy
                if 0 <= X < 256 and 0 <= Y < 224:
                    c[Y, X] = pal[im[yy, xx]]
        frames.append(Image.fromarray(c).resize((256 * scale, 224 * scale), Image.NEAREST))
    return frames


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    ap.add_argument("--preview", type=Path)
    a = ap.parse_args(argv)
    a.out.mkdir(parents=True, exist_ok=True)
    img = crown_image()
    blob, ntiles = m7_blob(img)
    states, plan, records = G.compile_all()
    cmds, ptr = DF.command_bytes(plan)
    init = DF.init_bytes(plan)
    ptr += (len(cmds) + len(init)).to_bytes(2, "little")
    cmds = cmds + init
    (a.out / "dgng_m7.bin").write_bytes(blob)
    (a.out / "dgng_hero.bin").write_bytes(b"".join(GF.tiles_rowmajor(f) for f in GF.hero_frames()))
    pal = json.loads((CROWN / "palettes.json").read_text())["base"]
    (a.out / "dgng_pal.bin").write_bytes(pal_blob(pal))
    (a.out / "dgng_score.bin").write_bytes(pad(b"".join(records), SCORE_CLAIM, "the score"))
    (a.out / "dgng_cmds.bin").write_bytes(pad(cmds, CMDS_CLAIM, "the command stream"))
    (a.out / "dgng_ptr.bin").write_bytes(pad(ptr, PTR_CLAIM, "the pointer table"))
    (a.out / "dgng_frames.inc").write_text(inc_text())
    bs = G.boss_states()
    spin = max(abs(bs[t][0] - bs[t - 1][0]) for t in range(1, len(bs)))
    plane = G.plane_from_image(img)
    full = int((img > 0).sum() * G.SCALE ** 2)
    vis = [int((G.render_m7(plane, G.matrix_words(*bs[t])) > 0).sum()) for t in range(0, G.LOOP, 2)]
    report = {"ticks": G.LOOP, "unique_tiles": ntiles, "peak_spin_deg_per_tick": round(spin, 1),
              "visible_min": round(min(vis) / full, 3), "visible_max": round(max(vis) / full, 3),
              "stream": DF.stats(plan)}
    (a.out / "dgng_report.json").write_text(json.dumps(report))
    if a.preview:
        fr = render_preview(img, states, list(range(0, G.LOOP, 2)))
        fr[0].save(a.preview, save_all=True, append_images=fr[1:], duration=33, loop=0, optimize=False)
    print(f"gen_dgn_giant_assets: {G.LOOP} ticks, {ntiles} of 256 Mode 7 tiles, peak spin {spin:.1f} deg/tick, "
          f"crown {report['visible_min']:.0%}..{report['visible_max']:.0%} visible, stream peak {max(plan['bytes'])} B/tick")
    return 0


if __name__ == "__main__":
    sys.exit(main())
