#!/usr/bin/env python3
"""gen_dgn_hero_assets.py — the model spike's sprites, converted for the ROM.

    python3 tools/gen_dgn_hero_assets.py OUT_DIR

Reads ONLY committed inputs (the build never runs Blender, docs/dungeons/11):
  art/dungeons/actors/frames/wanderer_{idle,walk}_{right,up,down}.png
      the indexed strips (index 0 transparent), the palette-ROLE contract
  art/dungeons/actors/anchors.json     the measured foot point
  art/dungeons/actors/actions.toml     frame counts and holds
  art/dungeons/actors/sheets.py        the P1/P2 PREVIEW colours (the same
                                       ones the contact sheet shows)
and emits (byte-identical on re-run):
  dgnh_obj_chr.bin   6144 B: 192 OBJ tiles, 4bpp. Frame f is a 16x32 figure drawn
                     as TWO stacked 16x16 OBJs: the top at name f%8*2 + f//8*64
                     (tiles N, N+1, N+16, N+17 of the hardware's 16-wide OBJ name
                     table), the bottom at that name + 32. 8 frames per band
  dgnh_obj_pal.bin   64 B: OBJ palette 0 = P1, OBJ palette 1 = P2 (BGR555).
                     Indices ARE the roles.toml contract: only colours differ
  dgnh_frames.inc    counts, frame indices, holds and the anchor as ca65
                     equates + hold tables. Never an address (11 §5)

This is the spike's slice of 11 §5 stage 6. The full converter
(gen_dungeons_assets.py, obj_stream blobs) is M3's.
"""
from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

import numpy as np
from PIL import Image

REPO = Path(__file__).resolve().parents[1]
ACTORS = REPO / "art" / "dungeons" / "actors"
sys.path.insert(0, str(ACTORS))
import sheets  # noqa: E402  (the preview palettes; pure numpy + Pillow)

MODEL = "wanderer"
# Frame order in the CHR blob. The ROM's animation tables index into this.
STRIPS = [("idle", "right"), ("idle", "up"), ("idle", "down"),
          ("walk", "right"), ("walk", "up"), ("walk", "down")]
BAND = 8                     # 16x32 frames per 4-tile-row band (16 tiles wide)
                             # TICK: ok — ANIMATION frames per CHR band: VRAM layout, not time
BANDS = 3                    # 18 frames -> 3 bands = 96 tile slots
                             # TICK: ok — a count of CHR bands, not of video frames
BOX_W, BOX_H = 16, 32
TILE_ROWS = BOX_H // 8       # 4 tile rows per frame
                             # TICK: ok — OBJ tile rows per sprite: pixel geometry, not time


def encode_4bpp(tile: np.ndarray) -> bytes:
    """8x8 indices -> 32 B SNES 4bpp. An index > 15 is a refusal."""
    assert tile.shape == (8, 8) and int(tile.max()) <= 15
    lo, hi = bytearray(), bytearray()
    for row in tile:
        p = [sum(((int(v) >> b) & 1) << (7 - x) for x, v in enumerate(row)) for b in range(4)]
        lo += bytes((p[0], p[1]))
        hi += bytes((p[2], p[3]))
    return bytes(lo + hi)


def bgr555(rgb) -> int:
    r, g, b = (int(c) >> 3 for c in rgb)
    return r | (g << 5) | (b << 10)


def frames(act: dict):
    """[(strip_key, index_in_strip, 16x16 array)] in blob order."""
    out = []
    for name, d in STRIPS:
        a = np.asarray(Image.open(ACTORS / "frames" / f"{MODEL}_{name}_{d}.png"))
        n = act["action"][name]["frames"]
        assert a.shape == (BOX_H, BOX_W * n), f"{name}_{d}: {a.shape}"
        out += [((name, d), i, a[:, i * BOX_W:(i + 1) * BOX_W]) for i in range(n)]
    return out


def chr_blob(fr) -> bytes:
    assert len(fr) <= BAND * BANDS
    tiles = [bytes(32)] * (16 * TILE_ROWS * BANDS)  # unused slots: index 0
    for f, (_, _, img) in enumerate(fr):
        name = (f % BAND) * 2 + (f // BAND) * 16 * TILE_ROWS
        for ty in range(TILE_ROWS):
            for tx in range(2):
                tiles[name + ty * 16 + tx] = encode_4bpp(img[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8])
    return b"".join(tiles)


def pal_blob() -> bytes:
    words = []
    for pal in (sheets.P1, sheets.P2):
        assert len(pal) == 16
        words += [0] + [bgr555(c) for c in pal[1:]]  # index 0: transparent
    return b"".join(w.to_bytes(2, "little") for w in words)


def inc_text(fr, act: dict, anchor: dict) -> str:
    first = {}
    for f, (key, i, _) in enumerate(fr):
        first.setdefault(key, f)
    lines = ["; GENERATED by tools/gen_dgn_hero_assets.py: do not edit.",
             "; Frame indices into dgnh_obj_chr.bin, holds in game frames",
             "; (actions.toml), the measured anchor (anchors.json). No addresses.",
             f"DGNH_FRAMES = {len(fr)}",
             f"DGNH_BAND = {BAND}",
             f"DGNH_ANCHOR_X = {anchor['anchor_x']}",
             f"DGNH_ANCHOR_Y = {anchor['anchor_y']}",
             f"DGNH_BACKDROP_BGR = {bgr555(sheets.BG_FLOOR)}"]
    for (name, d), f in first.items():
        lines.append(f"DGNH_F_{name.upper()}_{d.upper()} = {f}")
    for name in ("idle", "walk"):
        hold = act["action"][name]["hold"]
        lines.append(f"DGNH_{name.upper()}_N = {len(hold)}")
    lines.append('.pushseg\n.segment "RODATA"')
    for name in ("idle", "walk"):
        hold = act["action"][name]["hold"]
        lines.append(f"dgnh_{name}_hold: .byte {', '.join(str(h) for h in hold)}")
    lines.append(".popseg")
    return "\n".join(lines) + "\n"


def main(argv) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    out = Path(argv[1])
    out.mkdir(parents=True, exist_ok=True)
    act = tomllib.loads((ACTORS / "actions.toml").read_text())
    anchor = json.loads((ACTORS / "anchors.json").read_text())["models"][MODEL]
    fr = frames(act)
    chr_ = chr_blob(fr)
    (out / "dgnh_obj_chr.bin").write_bytes(chr_)
    (out / "dgnh_obj_pal.bin").write_bytes(pal_blob())
    (out / "dgnh_frames.inc").write_text(inc_text(fr, act, anchor))
    print(f"gen_dgn_hero_assets: {len(fr)} frames, {len(chr_)} B CHR, 64 B palettes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
